test("non-UTF8 and NUL-containing edits fail before any batch member changes bytes", async () => {
  await fixture(async (root) => {
    const invoke = await tools(root);
    const invalid = Buffer.concat([Buffer.from("before"), Buffer.from([0xff, 0xfe])]);
    await fs.writeFile(path.join(root, "src/new.ts"), invalid);
    expect((await invoke("read", { path: "src/new.ts" })).isError).toBe(true);
    expect(output(await invoke("grep", { pattern: "before", path: "src/new.ts" }))).toBe(
      "No matches",
    );
    const result = await invoke("edit", {
      edits: [
        { path: "src/allowed.ts", old_string: "'before'", new_string: "'after'" },
        { path: "src/new.ts", old_string: "before", new_string: "after" },
      ],
    });
    expect(result.isError).toBe(true);
    expect(await fs.readFile(path.join(root, "src/new.ts"))).toEqual(invalid);
    expect(await fs.readFile(path.join(root, "src/allowed.ts"), "utf8")).toContain("'before'");
    const binary = Buffer.from("before\0retained");
    await fs.writeFile(path.join(root, "src/new.ts"), binary);
    expect(
      (
        await invoke("edit", {
          edits: [{ path: "src/new.ts", old_string: "before", new_string: "after" }],
        })
      ).isError,
    ).toBe(true);
    expect((await invoke("write", { path: "src/new.ts", content: "replacement\0" })).isError).toBe(
      true,
    );
    expect(await fs.readFile(path.join(root, "src/new.ts"))).toEqual(binary);
  });
});

test("published schemas reject malformed calls and runtime errors permit corrected retries", async () => {
  await fixture(async (root) => {
    const definitions = await createWorkerTools({
      root,
      cwd: root,
      files: ["src/allowed.ts", "src/new.ts"],
      settings: Settings.isolated({ "edit.blockAutoGenerated": false }),
    });
    const replacement = { path: "src/allowed.ts", old_string: "before", new_string: "after" };
    for (const [name, args] of [
      ["read", { path: "helper.ts", "i:": "<parameter=type>", content: "" }],
      ["read", { path: "helper.ts", offset: 1, limit: 20 }],
      ["write", { path: "src/new.ts", content: "", i: "Writing file" }],
      ["edit", {}],
      ["edit", { edits: '<SM:EDIT path="src/allowed.ts">' }],
      ["edit", { edits: ["src/allowed.ts"] }],
      ["edit", { edits: [{ path: "src/allowed.ts", original: "before", normalized: "after" }] }],
      ["edit", { edits: [] }],
      ["read", { path: "" }],
      ["read", { path: "helper.ts", startLine: 1.5 }],
      ["read", { path: "helper.ts", endLine: Number.MAX_SAFE_INTEGER + 1 }],
      ["glob", { pattern: "**/*", limit: 1001 }],
      ["grep", { pattern: "name", limit: 0 }],
      ["grep", { pattern: "name", path: "" }],
    ] as const) {
      const definition = definitions.find((entry) => entry.name === `conduct_${name}`)!;
      expect(() => (definition.parameters as Type).assert(args)).toThrow();
      const result = await definition.execute("malformed", args, undefined, {} as CustomToolContext);
      expect(result.isError).toBe(true);
      expect(result.details).toBeUndefined();
      expect(output(result)).toContain("JSON example:");
      expect(output(result)).not.toContain("fresh human-authorized scope");
    }
    const write = definitions.find((entry) => entry.name === "conduct_write")!;
    const valid = { path: "src/new.ts", content: "" };
    expect((write.parameters as Type).assert(valid)).toEqual(valid);
    const recovered = await write.execute("recovered", valid, undefined, {} as CustomToolContext);
    expect(recovered.isError).not.toBe(true);
    expect(recovered.details).toEqual({ changed: true });
    expect(await fs.readFile(path.join(root, "src/new.ts"), "utf8")).toBe("");
    const edit = definitions.find((entry) => entry.name === "conduct_edit")!;
    const recoveredEdit = await edit.execute(
      "recovered-edit",
      { edits: [replacement] },
      undefined,
      {} as CustomToolContext,
    );
    expect(recoveredEdit.isError).not.toBe(true);
    expect(recoveredEdit.details).toEqual({ changed: true });
    expect(await fs.readFile(path.join(root, "src/allowed.ts"), "utf8")).toBe(
      "export const name = 'after';\n",
    );
    expect((edit.parameters as Type).assert({
      edits: [{ ...replacement, new_string: "", replace_all: null }],
    })).toEqual({ edits: [{ ...replacement, new_string: "", replace_all: null }] });
    for (const [name, args] of [
      ["read", { path: "helper.ts", startLine: null, endLine: null }],
      ["glob", { pattern: "**/*", path: null, limit: null }],
      ["grep", { pattern: "", path: null, limit: null, ignoreCase: null }],
    ] as const) {
      const definition = definitions.find((entry) => entry.name === `conduct_${name}`)!;
      expect((definition.parameters as Type).assert(args)).toEqual(args);
    }
  });
});

test("writes distinguish UTF-8 no-ops, empty truncation and absent empty creation without rewriting", async () => {
  await fixture(async (root) => {
    const invoke = await tools(root);
    const target = path.join(root, "src/allowed.ts");
    const content = "\uFEFFé🙂\n";
    const first = await invoke("write", { path: "src/allowed.ts", content });
    expect(first.details).toEqual({ changed: true });
    expect(output(first)).toContain(`${Buffer.byteLength(content)} UTF-8 bytes`);
    const timestamp = new Date("2001-01-01T00:00:00Z");
    await fs.utimes(target, timestamp, timestamp);
    const before = await fs.stat(target, { bigint: true });
    const same = await invoke("write", { path: "src/allowed.ts", content });
    expect(same.details).toEqual({ changed: false });
    expect(output(same)).toContain("No change");
    expect((await fs.stat(target, { bigint: true })).mtimeNs).toBe(before.mtimeNs);
    expect(await fs.readFile(target)).toEqual(Buffer.from(content));

    const truncated = await invoke("write", { path: "src/allowed.ts", content: "" });
    expect(truncated.details).toEqual({ changed: true });
    expect(output(truncated)).toContain("0 UTF-8 bytes");
    expect(await fs.readFile(target)).toEqual(Buffer.alloc(0));
    await fs.utimes(target, timestamp, timestamp);
    const emptyBefore = await fs.stat(target, { bigint: true });
    const emptyAgain = await invoke("write", { path: "src/allowed.ts", content: "" });
    expect(emptyAgain.details).toEqual({ changed: false });
    expect(output(emptyAgain)).toContain("0 UTF-8 bytes");
    expect((await fs.stat(target, { bigint: true })).mtimeNs).toBe(emptyBefore.mtimeNs);
    const created = await invoke("write", { path: "src/new.ts", content: "" });
    expect(created.details).toEqual({ changed: true });
    expect(output(created)).toContain("0 UTF-8 bytes");
    expect(await fs.readFile(path.join(root, "src/new.ts"))).toEqual(Buffer.alloc(0));
  });
});

test("unchanged native edits preserve bytes and mixed failures remain atomic", async () => {
  await fixture(async (root) => {
    const invoke = await tools(root);
    const target = path.join(root, "src/allowed.ts");
    const other = path.join(root, "src/new.ts");
    await fs.writeFile(target, "\uFEFFbefore é\n");
    await fs.writeFile(other, "before\n");
    const timestamp = new Date("2001-01-01T00:00:00Z");
    await fs.utimes(target, timestamp, timestamp);
    const before = await fs.stat(target, { bigint: true });
    const noop = { path: "src/allowed.ts", old_string: "before", new_string: "before" };
    const unchanged = await invoke("edit", { edits: [noop] });
    expect(unchanged.isError).toBe(true);
    expect(unchanged.details).toBeUndefined();
    expect((await fs.stat(target, { bigint: true })).mtimeNs).toBe(before.mtimeNs);
    const mixed = await invoke("edit", {
      edits: [
        { path: "src/new.ts", old_string: "before", new_string: "" },
        noop,
      ],
    });
    expect(mixed.isError).toBe(true);
    expect(mixed.details).toBeUndefined();
    expect(await fs.readFile(other, "utf8")).toBe("before\n");
    expect(await fs.readFile(target)).toEqual(Buffer.from("\uFEFFbefore é\n"));
    expect((await fs.stat(target, { bigint: true })).mtimeNs).toBe(before.mtimeNs);
    const corrected = await invoke("edit", {
      edits: [
        { path: "src/allowed.ts", old_string: "before", new_string: "after" },
        { path: "src/new.ts", old_string: "before", new_string: "" },
      ],
    });
    expect(corrected.isError).not.toBe(true);
    expect(corrected.details).toEqual({ changed: true });
    expect(await fs.readFile(target)).toEqual(Buffer.from("\uFEFFafter é\n"));
    expect(await fs.readFile(other, "utf8")).toBe("\n");
  });
});

