test("outside paths and native URI, selector, device, and multi-target transports are rejected", async () => {
  await fixture(async (root, outside) => {
    const invoke = await tools(root);
    const rejected = [
      outside,
      "../outside.txt",
      "https://example.com",
      "file:///etc/passwd",
      "local://escape",
      "artifact://escape",
      "ssh://host/etc/passwd",
      "xd://bash",
      "src/allowed.ts:raw",
      "src/allowed.ts%3Araw",
      "src/allowed.ts;../outside.txt",
      "archive.zip:src/allowed.ts",
      "database.db:users",
      "attachment://0",
      "src/allowed.ts\n../outside.txt",
    ];
    for (const target of rejected) {
      expect((await invoke("read", { path: target })).isError).toBe(true);
      expect((await invoke("write", { path: target, content: "overwrite" })).isError).toBe(true);
      expect(
        (
          await invoke("edit", {
            edits: [{ path: target, old_string: "before", new_string: "overwrite" }],
          })
        ).isError,
      ).toBe(true);
    }
    expect(await fs.readFile(outside, "utf8")).toBe("outside-secret");
    expect(await fs.readFile(path.join(root, "src/allowed.ts"), "utf8")).toContain("before");
  });
});

test("symlinks and Git metadata are neither traversed by discovery nor directly accessible", async () => {
  await fixture(async (root, outside) => {
    await fs.mkdir(path.join(root, ".git"));
    await fs.writeFile(path.join(root, ".git", "config"), "metadata-secret");
    await fs.symlink(outside, path.join(root, "linked.txt"));
    await fs.symlink(path.dirname(outside), path.join(root, "linked-dir"));
    await fs.link(outside, path.join(root, "hard-linked.txt"));
    const invoke = await tools(root);
    for (const target of [
      "linked.txt",
      "linked-dir/outside.txt",
      "hard-linked.txt",
      ".git/config",
      "src/../.git/config",
    ]) {
      expect((await invoke("read", { path: target })).isError).toBe(true);
      expect((await invoke("grep", { pattern: "secret", path: target })).isError).toBe(true);
    }
    const listing = output(await invoke("glob", { pattern: "**/*" }));
    expect(listing).toContain("helper.ts");
    expect(listing).not.toContain("linked");
    expect(listing).not.toContain(".git");
    const results = output(await invoke("grep", { pattern: "secret" }));
    expect(results).toContain("neighbor-secret");
    expect(results).not.toContain("outside-secret");
    expect(results).not.toContain("metadata-secret");
    for (const pattern of ["../**", "**/.git/**", "local://**", "**;../*"]) {
      expect((await invoke("glob", { pattern })).isError).toBe(true);
    }
  });
});

test("a symlink substituted after dispatch cannot redirect an allowed write or its ancestor", async () => {
  await fixture(async (root, outside) => {
    const invoke = await tools(root);
    await fs.unlink(path.join(root, "src/allowed.ts"));
    await fs.symlink(outside, path.join(root, "src/allowed.ts"));
    expect((await invoke("write", { path: "src/allowed.ts", content: "changed" })).isError).toBe(
      true,
    );
    await fs.unlink(path.join(root, "src/allowed.ts"));
    await fs.rmdir(path.join(root, "src"));
    await fs.symlink(path.dirname(outside), path.join(root, "src"));
    expect((await invoke("write", { path: "src/new.ts", content: "changed" })).isError).toBe(true);
    expect(await fs.readFile(outside, "utf8")).toBe("outside-secret");
    expect(await Bun.file(path.join(path.dirname(outside), "new.ts")).exists()).toBe(false);
  });
});

